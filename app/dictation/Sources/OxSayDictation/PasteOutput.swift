import AppKit
import Carbon
import DictationCore

/// NSPasteboard.general as a DictationPasteboard.
///
/// With `promised`, dictated text is written as a promise: the pasteboard asks
/// this app for the text when another app reads it, and `readAt` records when
/// that happened, which tells PasteOutput the paste has been taken. It is also
/// marked transient, so clipboard managers leave it out of their history.
final class SystemPasteboard: NSObject, DictationPasteboard, NSPasteboardItemDataProvider {
    private let pasteboard = NSPasteboard.general
    private let promised: Bool
    private var text = ""
    /// When an app first read the promised text since the last write.
    private(set) var readAt: Date?

    init(promised: Bool) {
        self.promised = promised
    }

    var changeCount: Int { pasteboard.changeCount }

    var declaredItems: [[String]] {
        (pasteboard.pasteboardItems ?? []).map { $0.types.map(\.rawValue) }
    }

    func data(item index: Int, forType type: String) -> Data? {
        guard let items = pasteboard.pasteboardItems, items.indices.contains(index) else { return nil }
        return items[index].data(forType: NSPasteboard.PasteboardType(type))
    }

    @discardableResult
    func writeText(_ text: String) -> Int {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        if promised {
            self.text = text
            readAt = nil
            item.setDataProvider(self, forTypes: [.string])
            item.setData(Data(), forType: NSPasteboard.PasteboardType(PasteboardMarker.transient))
        } else {
            item.setString(text, forType: .string)
        }
        item.setData(Data(), forType: NSPasteboard.PasteboardType(PasteboardMarker.autoGenerated))
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }

    /// The plain-text contents, for the speak-selection ⌘C read.
    func readText() -> String? {
        pasteboard.string(forType: .string)
    }

    func restore(_ snapshot: PasteboardSnapshot) {
        pasteboard.clearContents()
        let items = snapshot.restorableItems.map { entries -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for entry in entries { item.setData(entry.data, forType: NSPasteboard.PasteboardType(entry.type)) }
            // The user's copy is already in any clipboard history; putting it back
            // is not a new copy.
            for marker in PasteboardMarker.restored { item.setData(Data(), forType: NSPasteboard.PasteboardType(marker)) }
            return item
        }
        if !items.isEmpty { pasteboard.writeObjects(items) }
    }

    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        if readAt == nil { readAt = Date() }
        item.setString(text, forType: type)
    }
}

/// Puts dictated text where the cursor is: borrows the clipboard, sends Cmd+V to
/// the frontmost app and gives the clipboard back once the app has read it. When
/// the clipboard holds a Universal Clipboard copy, which cannot be put back
/// without fetching it from the other device, the text is typed with Unicode
/// key events instead and the clipboard is never touched. When pasting is not
/// allowed or not safe, the text stays on the clipboard and `onNotice` says why.
final class PasteOutput: TextOutput {
    var onNotice: ((String) -> Void)?
    /// The clipboard could not be put back when the paste settled, seconds
    /// after `deliver` returned: about a paste that already happened, so the
    /// app must not tie it to whichever dictation is running by then.
    var onLateNotice: ((String) -> Void)?
    /// When a posted paste settles: whether the target app read the promised
    /// clipboard before the 3 s cap. `false` is what a paste that went nowhere
    /// looks like; feeds the `paste settled` log line.
    var onPasteSettled: ((Int, Bool) -> Void)?
    /// Counts every `deliver`; the id a timing line and the `paste settled`
    /// line of the same delivery share.
    private(set) var deliverySerial = 0
    /// A posted paste settled unread and the user's clipboard went back: the
    /// dictation is on neither the screen nor the clipboard, only in the
    /// history. The app says so, and the clipboard stays the user's.
    var onPasteUnread: (() -> Void)?
    /// The clipboard held a copy from another device (Universal Clipboard), so
    /// the text was posted as synthetic key events and the clipboard left
    /// alone: character count and seconds the posting took (the time to
    /// enqueue the events, not to deliver them). A log line, not a notice.
    var onTypedOverRemoteClipboard: ((Int, TimeInterval) -> Void)?
    /// The app that had focus when the recording stopped; the paste goes there
    /// or nowhere.
    var target: pid_t?

    private let lending = SystemPasteboard(promised: true)
    private let plain = SystemPasteboard(promised: false)
    /// A paste whose clipboard has not been given back yet.
    private var pending: (lease: ClipboardLease, timer: Timer, text: String, serial: Int)?

    func deliver(_ text: String) -> Delivery { deliver(text, to: target) }

    /// Delivers to an explicit app, leaving `target` — the in-flight
    /// dictation's — untouched (Paste Last Dictation).
    func deliver(_ text: String, to target: pid_t?) -> Delivery {
        // A previous paste still waiting for its read: give its clipboard back
        // now, so this one borrows the user's contents and not the old dictation.
        settle()
        deliverySerial += 1
        let front = NSWorkspace.shared.frontmostApplication?.processIdentifier
        let moved = target != nil && front != target
        // Declared types only: reading a Universal Clipboard copy makes macOS
        // fetch it from the other device. Decided before any lease exists — a
        // ClipboardLease writes the text at init, which would destroy the copy.
        let remote = plain.holdsRemoteCopy
        switch OutputPolicy.decide(secureInput: IsSecureEventInputEnabled(), focusMoved: moved,
                                   accessibilityTrusted: AXIsProcessTrusted(), clipboardRemote: remote) {
        case .clipboardOnly(let reason):
            plain.writeText(text)
            onNotice?(reason.message)
            return .clipboardOnly(reason: reason)
        case .typed:
            let started = Date()
            postTypedText(text)
            onTypedOverRemoteClipboard?(text.count, Date().timeIntervalSince(started))
            return .typed
        case .paste:
            let lease = ClipboardLease(board: lending, text: text)
            let posted = Date()
            postCommandV()
            // Give the clipboard back once the app has read the text and had a
            // moment to finish the paste; if it never reads it (the field takes no
            // paste), after 3 s. Restoring before the read would paste the user's
            // previous clipboard instead of the dictation.
            let timer = Timer.scheduledTimer(withTimeInterval: 0.05, repeats: true) { [weak self, lending] _ in
                let now = Date()
                let read = lending.readAt.map { now.timeIntervalSince($0) >= 0.2 } ?? false
                if (read && now.timeIntervalSince(posted) >= 0.3) || now.timeIntervalSince(posted) >= 3 {
                    self?.settle()
                }
            }
            pending = (lease, timer, text, deliverySerial)
            return .paste
        }
    }

    /// Gives a borrowed clipboard back now. Also called before the app quits: the
    /// promised text dies with the process and would leave the clipboard empty.
    func settle() {
        guard let pending else { return }
        self.pending = nil
        pending.timer.invalidate()
        PasteSettlement.settle(lease: pending.lease, text: pending.text, read: lending.readAt != nil, plain: plain,
                               onSettled: { [onPasteSettled, serial = pending.serial] read in onPasteSettled?(serial, read) },
                               onNotice: onLateNotice, onUnread: onPasteUnread)
    }

    /// Types `text` into the frontmost app: key events carrying Unicode
    /// strings, posted the way ⌘V is, at most 20 UTF-16 units per event. The
    /// clipboard is never touched.
    private func postTypedText(_ text: String) {
        let source = CGEventSource(stateID: .combinedSessionState)
        for chunk in TypingChunks.split(text) {
            let units = Array(chunk.utf16)
            for isDown in [true, false] {
                let event = CGEvent(keyboardEventSource: source, virtualKey: 0, keyDown: isDown)
                // No modifiers: one still held from the hotkey must not turn
                // the characters into shortcuts.
                event?.flags = []
                event?.keyboardSetUnicodeString(stringLength: units.count, unicodeString: units)
                event?.post(tap: .cghidEventTap)
            }
        }
    }

    private func postCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let v = CGKeyCode(PasteKey.commandV(lookup: PasteOutput.layoutCharacter()))
        // Only Command: a modifier still held from the hotkey must not turn this into ⌃⌘V.
        let down = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: true)
        down?.flags = .maskCommand
        let up = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: false)
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    /// Maps a virtual key code to the character it types with ⌘ held in the
    /// current keyboard layout, via UCKeyTranslate on the live TIS layout data.
    /// ⌘ matters: some layouts switch tables under it ("Dvorak – QWERTY ⌘"
    /// types QWERTY, Russian types Latin). The closure holds the layout bytes, so one paste scans the
    /// keyboard once. A dead key or a key that types nothing maps to nil, as
    /// does every key when the layout cannot be read at all.
    static func layoutCharacter() -> (Int) -> Character? {
        guard let data = layoutData() else { return { _ in nil } }
        let keyboardType = UInt32(LMGetKbdType())
        return { keyCode in
            data.withUnsafeBytes { raw -> Character? in
                guard let layout = raw.baseAddress?.assumingMemoryBound(to: UCKeyboardLayout.self) else { return nil }
                var deadKeyState: UInt32 = 0
                var length = 0
                var chars = [UniChar](repeating: 0, count: 4)
                let commandHeld = UInt32((cmdKey >> 8) & 0xFF)
                guard UCKeyTranslate(layout, UInt16(keyCode), UInt16(kUCKeyActionDown), commandHeld,
                                     keyboardType, UInt32(kUCKeyTranslateNoDeadKeysMask),
                                     &deadKeyState, chars.count, &length, &chars) == noErr,
                      length > 0 else { return nil }
                return String(utf16CodeUnits: chars, count: length).first
            }
        }
    }

    /// The current layout's UCKeyTranslate data; the ASCII-capable layout's
    /// when the current input source does not carry key layout data.
    private static func layoutData() -> Data? {
        func uchr(_ source: TISInputSource?) -> Data? {
            guard let source, let ref = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData) else {
                return nil
            }
            // The CFData belongs to `source` (Get rule): bridge it while the
            // source is alive; the Data then keeps its own reference.
            return withExtendedLifetime(source) { Unmanaged<CFData>.fromOpaque(ref).takeUnretainedValue() as Data }
        }
        return uchr(TISCopyCurrentKeyboardLayoutInputSource()?.takeRetainedValue())
            ?? uchr(TISCopyCurrentASCIICapableKeyboardLayoutInputSource()?.takeRetainedValue())
    }
}
